import { readdir, readFile, stat, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourceRoot = join(repoRoot, "content", "skills", "agency-agents");
const outputPath = join(repoRoot, "apps", "desktop", "src", "generated-agency-agent-catalog.ts");

async function listMarkdownFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = await Promise.all(entries.map(async (entry) => {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) return listMarkdownFiles(path);
    return entry.isFile() && entry.name.endsWith(".md") ? [path] : [];
  }));
  return files.flat().sort();
}

function frontmatterValue(source, key) {
  const header = source.match(/^---\r?\n([\s\S]*?)\r?\n---/u)?.[1] ?? "";
  const value = header.match(new RegExp(`^${key}:\\s*(.+)$`, "mu"))?.[1]?.trim();
  return value?.replace(/^['"]|['"]$/g, "") ?? "";
}

function runtimeAgentId(category, sourcePath) {
  const fileSlug = sourcePath.replace(/\.md$/iu, "").replaceAll("/", "-");
  return fileSlug.startsWith(`${category}-`) ? `agency-${fileSlug}` : `agency-${category}-${fileSlug}`;
}

const categories = (await readdir(sourceRoot, { withFileTypes: true })).filter((entry) => entry.isDirectory()).map((entry) => entry.name).sort();
const sourceFiles = [];
for (const category of categories) {
  const categoryRoot = join(sourceRoot, category);
  for (const path of await listMarkdownFiles(categoryRoot)) {
    const metadata = await stat(path);
    sourceFiles.push({ category, path, size: metadata.size, modified: metadata.mtimeMs });
  }
}
const fingerprint = createHash("sha256").update(sourceFiles.map(({ category, path, size, modified }) => {
  const relativePath = relative(categoryRootFor(category), path).replaceAll("\\", "/");
  return `${category}/${relativePath}:${size}:${modified}`;
}).join("\n")).digest("hex");
const fingerprintedHeader = `// Source fingerprint: ${fingerprint}`;
try {
  const existing = await readFile(outputPath, "utf8");
  if (existing.startsWith(`${fingerprintedHeader}\n`)) {
    console.log(`Agency-agent catalog is unchanged (${sourceFiles.length} descriptors)`);
    process.exit(0);
  }
} catch {
  // The generated catalog is expected to be absent on a clean checkout.
}

function categoryRootFor(category) { return join(sourceRoot, category); }

const records = [];
for (const category of categories) {
  const categoryRoot = join(sourceRoot, category);
  for (const path of await listMarkdownFiles(categoryRoot)) {
    const sourcePath = relative(categoryRoot, path).replaceAll("\\", "/");
    const raw = await readFile(path, "utf8");
    records.push({
      id: runtimeAgentId(category, sourcePath),
      category,
      sourcePath,
      sourceUrl: `https://github.com/msitarzewski/agency-agents/blob/main/${category}/${sourcePath}`,
      name: frontmatterValue(raw, "name"),
      description: frontmatterValue(raw, "description"),
    });
  }
}

await writeFile(outputPath, `${fingerprintedHeader}\n// Generated by scripts/generate-desktop-agency-agent-catalog.mjs.\nexport const DESKTOP_AGENCY_AGENT_CATALOG = ${JSON.stringify(records, null, 2)} as const;\n`, "utf8");
console.log(`Generated ${records.length} desktop agency-agent descriptors at ${outputPath}`);
